import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ensChainId, outDir, rpcsFor, type LoadedConfig } from './config';

const REPO = fileURLToPath(new URL('../../..', import.meta.url));

/** docker compose service for the watcher, from copeybara.config.ts. The key itself goes in watcher.env, never here. */
export function watcherCompose(l: LoadedConfig, dir: string): { compose: string; envExample: string } {
  const { cfg } = l;
  if (!cfg.watcher) throw new Error('add watcher: { key: <address granted status + blocklist> } to the config');
  const candidates = cfg.watcher.candidates ?? [];
  const env: Record<string, string> = {
    WATCH_NAMES: cfg.name,
    WATCHER_ADDRESS: cfg.watcher.key,
    RPCS: rpcsFor(cfg, ensChainId(cfg)).join(','),
    INTERVAL_MS: String(cfg.watcher.intervalMs ?? 15000),
    STATUS_PORT: '8787',
    ...(candidates.length ? { CANDIDATES: `${cfg.name}=${candidates.join(',')}` } : {}),
  };
  const ctx = relative(dir, REPO) || '.';
  const compose = `# Generated by \`copeybara watcher\` from copeybara.config.ts. Re-run after changing the config.
services:
  watcher:
    build:
      context: ${JSON.stringify(ctx)}
      dockerfile: apps/watcher/Dockerfile
    restart: unless-stopped
    env_file: watcher.env
    environment:
${Object.entries(env).map(([k, v]) => `      ${k}: ${JSON.stringify(v)}`).join('\n')}
    read_only: true
    tmpfs: [/tmp]
    security_opt: [no-new-privileges:true]
`;
  const envExample = `# The watcher's own key: it may write org.copeybara.status and org.copeybara.blocklist ONLY (Safe grant via
# \`copeybara propose\`). Never a Safe owner key. Copy to watcher.env and keep that file out of git.
WATCHER_KEY=
# WRITE_RPC=https://...           # where it sends its two kinds of writes (default: first of RPCS)
# ANTHROPIC_API_KEY=              # optional: plain-language incident notes
`;
  return { compose, envExample };
}

export async function watcherCmd(l: LoadedConfig, o: { up: boolean }) {
  const dir = join(outDir(l), 'watcher');
  await mkdir(dir, { recursive: true });
  const { compose, envExample } = watcherCompose(l, dir);
  await writeFile(join(dir, 'compose.yml'), compose);
  await writeFile(join(dir, 'watcher.env.example'), envExample);
  await writeFile(join(dir, '.gitignore'), 'watcher.env\n');
  const rel = relative(process.cwd(), dir);
  process.stdout.write(`wrote ${rel}/compose.yml and watcher.env.example\n`);
  if (!existsSync(join(dir, 'watcher.env'))) {
    process.stdout.write(`next: cp ${rel}/watcher.env.example ${rel}/watcher.env, set WATCHER_KEY, then copeybara watcher --up\n`);
    return;
  }
  if (!o.up) return void process.stdout.write(`start: docker compose -f ${rel}/compose.yml up -d --build   (health: docker compose ps → healthy)\n`);
  const r = spawnSync('docker', ['compose', '-f', join(dir, 'compose.yml'), 'up', '-d', '--build'], { stdio: 'inherit' });
  if (r.status !== 0) process.exitCode = r.status ?? 1;
}
