// Writes dist/sw.js: an offline copy of this site and the exact hosted kit, so both keep opening when the website is down.
// Network first: a working site always wins; the cache answers only when the site is unreachable or erroring.
// It protects against the site going DOWN, not against it being HIJACKED. For that, the kit's sha256 is checked against ENS.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const dist = fileURLToPath(new URL('../dist/', import.meta.url));
const walk = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
const files = walk(dist)
  .map((f) => relative(dist, f).split('\\').join('/'))
  .filter((f) => f !== 'sw.js' && f !== 'index.html')
  .sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(dist, f)));
hash.update(readFileSync(join(dist, 'index.html')));
const version = hash.digest('hex').slice(0, 12);
const precache = ['./', ...files];

writeFileSync(
  join(dist, 'sw.js'),
  `// Generated by apps/site/scripts/write-sw.mjs. Offline copy of this site and the hosted kit.
// Network first; the cache answers only when the website is unreachable or erroring.
// This covers the site going DOWN, not being HIJACKED: verify the kit's sha256 against ENS.
const CACHE = 'copeybara-${version}';
const PRECACHE = ${JSON.stringify(precache)};
self.addEventListener('install', (e) => e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting())));
self.addEventListener('activate', (e) =>
  e.waitUntil(
    caches.keys()
      .then((ks) => Promise.all(ks.filter((k) => (k.startsWith('copeybara-') || k.startsWith('blackout-')) && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  ),
);
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(
    (async () => {
      const cached = () => caches.match(req, { ignoreSearch: true });
      try {
        const res = await fetch(req);
        if (res.ok) {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy));
          return res;
        }
        return (await cached()) ?? res;
      } catch (err) {
        const hit = await cached();
        if (hit) return hit;
        throw err;
      }
    })(),
  );
});
`,
);
console.log(`sw.js written (${precache.length} files, cache copeybara-${version})`);
